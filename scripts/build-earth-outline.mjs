/**
 * Generates src/components/simulation/earthLand.ts, the Earth's land masses as seen from
 * above the North Pole (Lambert azimuthal equal-area projection, clipped at 25°S).
 *
 * Source data: Natural Earth 1:110m land (public domain), https://www.naturalearthdata.com
 *   curl -L -o land.geojson https://raw.githubusercontent.com/nvkelso/natural-earth-vector/master/geojson/ne_110m_land.geojson
 *   node scripts/build-earth-outline.mjs land.geojson
 */
import fs from "node:fs";

const [input] = process.argv.slice(2);
if (!input) throw new Error("Usage: node scripts/build-earth-outline.mjs <ne_110m_land.geojson>");

const CLIP_LAT = -25;
const RADIUS = 50; // output: a disc of radius 50 centred on (0, 0)
const TOLERANCE = 0.005; // simplification tolerance, in unit-disc coordinates

const maxColat = ((90 - CLIP_LAT) * Math.PI) / 180;
const rMax = Math.sin(maxColat / 2);

/** North-polar equal-area projection. Greenwich points down; east runs counter-clockwise. */
function project([lon, lat]) {
  const clamped = Math.max(lat, CLIP_LAT);
  const colat = ((90 - clamped) * Math.PI) / 180;
  const r = Math.sin(colat / 2) / rMax;
  const theta = (lon * Math.PI) / 180;
  return [r * Math.sin(theta), r * Math.cos(theta)];
}

function perpendicularDistance([px, py], [ax, ay], [bx, by]) {
  const dx = bx - ax;
  const dy = by - ay;
  const len = Math.hypot(dx, dy);
  if (len === 0) return Math.hypot(px - ax, py - ay);
  return Math.abs(dy * px - dx * py + bx * ay - by * ax) / len;
}

function simplify(points, tolerance) {
  if (points.length < 3) return points;
  let maxDist = 0;
  let index = 0;
  for (let i = 1; i < points.length - 1; i++) {
    const d = perpendicularDistance(points[i], points[0], points[points.length - 1]);
    if (d > maxDist) { maxDist = d; index = i; }
  }
  if (maxDist <= tolerance) return [points[0], points[points.length - 1]];
  const left = simplify(points.slice(0, index + 1), tolerance);
  const right = simplify(points.slice(index), tolerance);
  return [...left.slice(0, -1), ...right];
}

function area(points) {
  let a = 0;
  for (let i = 0; i < points.length; i++) {
    const [x1, y1] = points[i];
    const [x2, y2] = points[(i + 1) % points.length];
    a += x1 * y2 - x2 * y1;
  }
  return Math.abs(a) / 2;
}

const geo = JSON.parse(fs.readFileSync(input, "utf8"));
const rings = [];
for (const feature of geo.features) {
  const { type, coordinates } = feature.geometry;
  const polygons = type === "Polygon" ? [coordinates] : coordinates;
  for (const polygon of polygons) {
    const outer = polygon[0];
    if (outer.every(([, lat]) => lat < CLIP_LAT)) continue; // e.g. Antarctica
    const projected = simplify(outer.map(project), TOLERANCE);
    if (projected.length < 4 || area(projected) < 0.0004) continue;
    rings.push(projected);
  }
}

const fmt = (n) => (Math.round(n * RADIUS * 10) / 10).toString();
const path = rings
  .map((ring) => "M" + ring.map(([x, y]) => `${fmt(x)} ${fmt(y)}`).join("L") + "Z")
  .join("");

const out = new URL("../src/components/simulation/earthLand.ts", import.meta.url);
fs.writeFileSync(
  out,
  `// Generated by scripts/build-earth-outline.mjs from Natural Earth 1:110m land (public domain).\n` +
    `// North-polar equal-area projection clipped at ${-CLIP_LAT}°S, disc of radius ${RADIUS} centred on (0, 0).\n` +
    `export const EARTH_LAND_PATH =\n  "${path}";\n`,
);
console.log(`${rings.length} land polygons, ${path.length} characters`);
